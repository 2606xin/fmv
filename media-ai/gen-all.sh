#!/bin/bash
# 批量生成《零点接头》全部 AI 素材：生图 → 裁水印 → 统一规格
# 用法: bash gen-all.sh
set -e
cd "$(dirname "$0")"
FF=$(python3 -c "import imageio_ffmpeg; print(imageio_ffmpeg.get_ffmpeg_exe())")
GEN=~/.agents/skills/ark-imagegen/scripts/ark-imagegen
W=2560; H=1440; CROP_H=1296   # 裁掉底部10%去水印再回缩

STYLE="风格: 电影感写实摄影，1994年中国沿海小城，90年代胶片质感，青橙夜色调，细腻颗粒。约束: 无文字、无水印、无现代元素(无智能手机/LED屏/现代汽车)、画面干净。"

gen() { # $1=文件名 $2=提示词
  local name="$1"
  if [ -f "$name" ]; then echo "跳过已有: $name"; return; fi
  echo "生成: $name"
  local raw="raw-$name"
  $GEN "$2" "$raw" "${W}x${H}" >/dev/null 2>&1
  "$FF" -y -loglevel error -i "$raw" -vf "crop=${W}:${CROP_H}:0:0,scale=${W}:${H}" "$name"
  rm -f "$raw"
}

